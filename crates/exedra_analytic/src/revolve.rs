    fn mesh_volume(mesh: &exedra_mesh::Mesh) -> f64 {
        mesh.faces()
            .map(|f| {
                let p: Vec<_> = mesh
                    .face_loop(f)
                    .map(|c| {
                        mesh.vertex_position(mesh.from_vertex(c).unwrap())
                            .unwrap()
                            .map(f64::from)
                    })
                    .collect();
                assert_eq!(p.len(), 3);
                exedra_math::dot(p[0], exedra_math::cross(p[1], p[2])) / 6.0
            })
            .sum()
    }
